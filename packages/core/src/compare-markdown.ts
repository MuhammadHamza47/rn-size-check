import { MIN_CHANGE_BYTES, percentChange, sideLabel, type ChangeKind, type Comparison, type Delta } from './compare.js';
import { formatBytes, formatDelta, shortPath } from './format.js';
import { CATEGORY_LABELS } from './types.js';

const SEVERITY_ICON = { error: '🔴', warn: '🟠', info: '🔵' } as const;
const KIND_LABEL: Record<ChangeKind, string> = { added: 'new', removed: 'removed', grew: 'grew', shrank: 'shrank' };

/** Rows per table, so a PR comment stays readable. */
const TOP = 10;

/** A compact Markdown comparison for pull requests and release notes. */
export function comparisonToMarkdown(c: Comparison): string {
  const target = [c.target.abi === 'all' ? 'all ABIs' : c.target.abi, c.target.density].filter(Boolean).join(', ');
  const name = c.new.packageName ? `${c.new.packageName} ` : '';
  const d = c.sizes.download;
  const lines = [
    `### 📦 App size: ${name}${sideLabel(c.old)} → ${sideLabel(c.new)}`,
    '',
    `**Download (${target}): ${formatBytes(d.old)} → ${formatBytes(d.new)} (${change(d)})** · Install: ${formatBytes(c.sizes.install.old)} → ${formatBytes(c.sizes.install.new)} (${formatDelta(c.sizes.install.change)})`,
  ];

  const categories = c.categories.filter((r) => Math.abs(r.change) >= MIN_CHANGE_BYTES);
  if (categories.length > 0) {
    lines.push('', '| Category | Before | After | Change |', '|---|---:|---:|---:|');
    for (const r of categories) {
      lines.push(`| ${CATEGORY_LABELS[r.category]} | ${formatBytes(r.old)} | ${formatBytes(r.new)} | ${formatDelta(r.change)} |`);
    }
  } else {
    lines.push('', 'No category changed by more than 1 KB.');
  }

  if (c.files && c.files.length > 0) {
    lines.push('', '**Biggest file changes**', '', '| File | Change | |', '|---|---:|---|');
    for (const f of c.files.slice(0, TOP)) lines.push(`| \`${shortPath(f.path)}\` | ${formatDelta(f.change)} | ${KIND_LABEL[f.kind]} |`);
    if (c.files.length > TOP) lines.push(`| *${c.files.length - TOP} more files* | | |`);
  }

  if (c.packages && c.packages.length > 0) {
    lines.push('', '**npm packages in the JS bundle**', '', '| Package | Change | |', '|---|---:|---|');
    for (const p of c.packages.slice(0, TOP)) lines.push(`| ${p.name} | ${formatDelta(p.change)} | ${KIND_LABEL[p.kind]} |`);
    if (c.packages.length > TOP) lines.push(`| *${c.packages.length - TOP} more packages* | | |`);
  }

  if (c.findings.added.length > 0) {
    lines.push('', '**New problems**', '');
    for (const f of c.findings.added) {
      lines.push(`- ${SEVERITY_ICON[f.severity]} ${f.title}${f.savings ? ` · saves ${formatBytes(f.savings)}` : ''}`);
    }
  }
  if (c.findings.worse.length > 0) {
    lines.push('', '**Got worse**', '');
    for (const f of c.findings.worse) lines.push(`- ${SEVERITY_ICON[f.severity]} ${f.title} (was: ${f.oldTitle})`);
  }
  if (c.findings.fixed.length > 0) {
    lines.push('', '**Fixed**', '');
    for (const f of c.findings.fixed) lines.push(`- ✅ ${f.title}`);
  }
  if (c.findings.better.length > 0) {
    lines.push('', '**Got better**', '');
    for (const f of c.findings.better) lines.push(`- ✅ ${f.title} (was: ${f.oldTitle})`);
  }

  for (const note of c.notes) lines.push('', `> ${note}`);
  lines.push('', '<sub>Generated by [rn-size-check](https://github.com/MuhammadHamza47/rn-size-check)</sub>');
  return lines.join('\n');
}

function change(d: Delta): string {
  const pct = percentChange(d);
  return pct ? `${formatDelta(d.change)}, ${pct}` : formatDelta(d.change);
}
